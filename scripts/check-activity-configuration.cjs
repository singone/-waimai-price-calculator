// 核对券互斥、跨入口保存和京东分摊，避免只验证表单显示。
require('./check-platform-fees.cjs');
const assert = require('node:assert/strict');
const { bestCouponOption, eligibleCouponOptions } = require('../src/domain/core.ts');
const { activityConfigurationErrors } = require('../src/domain/activity/configuration.ts');
const { parseBackendSnapshot } = require('../src/domain/backendSync.ts');
const { importBackendTable } = require('../src/domain/backendTableImport.ts');
const { defaultState, normalizeState } = require('../src/data/calculatorState.ts');
const coupon = (name, amount, stackableWithCoupons) => ({ enabled: true, name, threshold: 20, amount, stackableWithCoupons });
const pool = [coupon('单独使用券', 10, false), coupon('可叠加券A', 8, true), coupon('可叠加券B', 7, true)];
assert.equal(bestCouponOption(pool, 30, 2).amount, 15);
assert.equal(bestCouponOption(pool, 30, 1).amount, 10);
assert.equal(bestCouponOption([coupon('单独大券', 20, false), ...pool.slice(1)], 30, 3).amount, 20);
assert.equal(bestCouponOption(pool, 19, 2).amount, 0);
assert.equal(bestCouponOption(pool, 30, 0).amount, 0);
assert.equal(bestCouponOption([coupon('旧券A', 8), coupon('旧券B', 7)], 30, 2).amount, 15);
assert.ok(eligibleCouponOptions(pool, 30, 3).every(option => option.coupons.length <= 1 || option.coupons.every(c => c.stackableWithCoupons !== false)));
const empty = { fullReductions: [], coupons: [], redAddOns: [], jingdongSubsidyCoupons: [], discountActivities: [] };
assert.ok(activityConfigurationErrors({ ...empty, fullReductions: [{enabled:true,threshold:10,amount:11}] }).length);
const jd = { enabled:true,name:'补贴券',kind:'large',threshold:29,amount:20,merchantAmount:15,platformAmount:5,merchantExtraAmount:3,stackableWithLarge:false };
assert.deepEqual(activityConfigurationErrors({...empty,jingdongSubsidyCoupons:[jd]}), []);
assert.ok(activityConfigurationErrors({...empty,jingdongSubsidyCoupons:[{...jd,platformAmount:6}]}).length);
assert.ok(activityConfigurationErrors({...empty,jingdongSubsidyCoupons:[{...jd,kind:'small'}]}).length);
const snapshot = {version:1,platform:'meituan',storeName:'核对门店',observedAt:'2026-01-01T00:00:00+08:00',source:'活动中心 → 订单券',unsupportedRules:[],items:[{kind:'activity',field:'coupons',value:[{...pool[0],channel:'targeted',targetUser:'newCustomer',usageSuggestion:'后台已核对，同一订单不能叠加其他订单券'}]}]};
const parsed = parseBackendSnapshot(snapshot);
assert.equal(parsed.items[0].value[0].stackableWithCoupons, false);
assert.equal(parsed.items[0].value[0].targetUser, 'newCustomer');
const table = importBackendTable([{类别:'订单券',名称:'新客券',门槛:20,金额:3,状态:'启用',发放渠道:'定向发券',适用人群:'新客',可叠加其他订单券:'否',后台核对备注:'后台限定新客领取'}]);
const tableParsed = parseBackendSnapshot({...snapshot,items:table.items});
assert.equal(tableParsed.items[0].value[0].stackableWithCoupons, false);
assert.equal(tableParsed.items[0].value[0].channel, 'targeted');
const state = JSON.parse(JSON.stringify(defaultState));
state.stores[0].activities.meituan.coupons = parsed.items[0].value;
const saved = normalizeState(JSON.parse(JSON.stringify(state)));
assert.equal(saved.stores[0].activities.meituan.coupons[0].stackableWithCoupons, false);
assert.equal(saved.stores[0].activities.meituan.coupons[0].channel, 'targeted');
assert.throws(()=>parseBackendSnapshot({...snapshot,items:[{kind:'activity',field:'fullReductions',value:[{enabled:true,threshold:10,amount:11}]}]}));
console.log('订单券互斥最优选择、旧配置兼容、后台导入与保存、人群渠道保留、京东分摊校验：通过');
